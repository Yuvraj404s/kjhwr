"""
WindScope DA — Python backend (FastAPI).

Serves the Elexon BMRS day-ahead wind analytics over a clean REST API.

Two modes of operation:

  1. SNAPSHOT (default) — reads the precomputed static extracts from
    ../../frontend/public/data/*.json (regenerated by backend/scripts/fetch_and_process.py).
     Deterministic, instant, zero external calls. Used by the Vite dev server
     and by `docker compose up`.

  2. LIVE (set WINDSCOPE_LIVE=1) — re-fetches FUELHH & WINDFOR from Elexon on
     demand and recomputes the day-ahead/decision-time evaluation in-process.
     Same math as the ETL, exposed for auditability.

Endpoints
---------
  GET /api/health                     liveness probe
  GET /api/meta                       extraction provenance + decision rule
  GET /api/actuals                    metered half-hourly wind (Jan 2026)
  GET /api/forecast-da                day-ahead (decision-time) forecast vs actuals
  GET /api/metrics                    full accuracy evaluation (overall/lead/day/SP/hist)
  GET /api/evolution?date=YYYY-MM-DD  forecast evolution band + all runs for a delivery day
  GET /api/latest                     latest WINDFOR publish in feed
  GET /api/live/summary               LIVE mode only: fresh evaluation from Elexon

Run:  uvicorn server.main:app --port 8000 --reload
"""
import json
import math
import os
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Optional
from urllib.request import Request, urlopen

from fastapi import FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware

UTC = timezone.utc
ROOT = Path(__file__).resolve().parents[2]
DATA_DIR = ROOT / "frontend" / "public" / "data"
LIVE = os.environ.get("WINDSCOPE_LIVE", "0") == "1"

app = FastAPI(
    title="WindScope DA API",
    version="0.1.0",
    description="GB national wind day-ahead forecast vs. metered actuals — decision-time evaluation for UK day-ahead power procurement (Elexon BMRS: FUELHH actuals, WINDFOR forecasts).",
)
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["GET"],
    allow_headers=["*"],
)

_cache: dict = {}


def _load(name: str):
    if name in _cache:
        return _cache[name]
    path = DATA_DIR / name
    if not path.exists():
        raise HTTPException(404, f"Snapshot {name} not found. Run: python backend/scripts/fetch_and_process.py")
    with open(path) as f:
        _cache[name] = json.load(f)
    return _cache[name]


# ---------------- snapshot endpoints ----------------
@app.get("/api/health")
def health():
    return {"status": "ok", "mode": "live" if LIVE else "snapshot", "generatedAt": _load("meta.json")["generatedAt"]}


@app.get("/api/meta")
def meta():
    return _load("meta.json")


@app.get("/api/actuals")
def actuals():
    return _load("actuals.json")


@app.get("/api/forecast-da")
def forecast_da(date: Optional[str] = Query(None, description="Filter to a delivery date YYYY-MM-DD")):
    rows = _load("forecast_da.json")
    if date:
        rows = [r for r in rows if r["deliveryDate"] == date]
        if not rows:
            raise HTTPException(404, f"No decision-time forecast for {date} (scope: Jan 2026)")
    return rows


@app.get("/api/metrics")
def metrics():
    return _load("metrics.json")


@app.get("/api/evolution")
def evolution(date: str = Query(..., description="Delivery date YYYY-MM-DD")):
    m = _load("metrics.json")
    for day in m["evolution"]:
        if day["deliveryDate"] == date:
            return day
    raise HTTPException(404, f"No evolution data for {date} (scope: Jan 2026)")


@app.get("/api/latest")
def latest():
    try:
        return _load("latest_forecast.json")
    except HTTPException:
        raise HTTPException(404, "latest_forecast.json not present in snapshot")


# ---------------- live mode ----------------
BASE = "https://data.elexon.co.uk/bmrs/api/v1/datasets"


def _elexon(path: str):
    req = Request(f"{BASE}{path}", headers={"Accept": "application/json", "User-Agent": "windscope-api/0.1"})
    with urlopen(req, timeout=60) as r:
        return json.loads(r.read().decode())


@app.get("/api/live/summary")
def live_summary():
    if not LIVE:
        raise HTTPException(403, "Live mode disabled. Start with WINDSCOPE_LIVE=1 to enable on-demand Elexon re-evaluation.")
    rows = _elexon("/FUELHH/stream?settlementDateFrom=2026-01-30&settlementDateTo=2026-02-01&fuelType=WIND")
    wind = sorted((r for r in rows if r["fuelType"] == "WIND"), key=lambda r: r["startTime"])
    gens = [r["generation"] for r in wind]
    return {
        "source": "Elexon FUELHH (live)",
        "nPoints": len(gens),
        "meanMW": round(sum(gens) / len(gens), 1) if gens else None,
        "maxMW": max(gens) if gens else None,
        "minMW": min(gens) if gens else None,
        "asOf": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }
